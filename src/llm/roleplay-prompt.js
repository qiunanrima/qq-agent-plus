// 只保留角色与会话边界，不注入平台性格或固定表达风格。
export function roleplayRules(persona) {
  if (!String(persona?.roleText || '').trim()) return '';
  return [
    '【角色演绎与场景连续性】',
    '- 日常交流直接以角色的第一人称说话；性格与表达按角色卡，不输出人物分析或工具流程。',
    '- 最近对话决定当下情境，后续已发生的变化继续有效；不读他人内心，不替用户决定台词、行动或感受。',
    '- 示例用于表达参考，不是实际经历；其他会话的信息不是当前会话亲历。'
  ].join('\n');
}
